/**
 * 校验台（id=validate）。这轮修的是八处误判，全都会印在页面上，所以逐条盯「页面上那行字」：
 *   身份证未来的出生日期（原来通过并印「-1 岁」）、网址端口（:0 / :99999 原来印格式正确）、
 *   邮箱域名标签连字符开头结尾与用户名的点、车牌末位挂/学/警（真车牌原来判「格式不正确」）、
 *   姓名首尾间隔号、手机号不再瞎猜运营商（138 原来印「联通/电信」）、
 *   IPv4 分类改读 ip.js 那张表（0.0.0.0 原来印「公网地址」）。
 *
 * 这一页的输入框是普通文本框（不是 type="digit"），字母和符号能打进去，
 * 所以「非法输入被判不通过」这类分支在这儿是真能验的——单位页做不到。
 * 切类型走「全部类型」那一列（.type-item）：顶部 PkSeg 是横向 scroll-view，
 * 第 9 项「统一社会信用代码」在 420px 视口里本来就看不见。
 */
import { IN, AREA, MINI, SEG, TYPE, BTN } from '../harness.mjs'

export default {
  name: 'validate',
  id: 'validate',
  height: 1500,
  check: async ({ page, ok }) => {
    const kinds = await page.evaluate(() => [...document.querySelectorAll('input.uni-input-input')].map((e) => e.type))
    ok(kinds[0] === 'text', '值输入框是普通文本框（才谈得上「字母打进去被拒」）：' + JSON.stringify(kinds))
  },
  steps: [
    { desc: '默认手机号：填合法号通过，只给号段', act: [[IN(0), '13800138000']],
      expect: ['通过', '号段 138'], forbid: ['运营商', '联通', '移动', '电信'] },
    { desc: '带空格照样认，并把去分隔符后的串回显', act: [[IN(0), '138 0013 8000']],
      expect: ['已自动去除分隔符 13800138000', '通过', '号段 138'] },
    { desc: '12 开头的号段判不通过', act: [[IN(0), '12800138000']],
      expect: ['不通过', '号段不存在或不是常见号段'] },
    { desc: '「示例」按钮填进去的一定能通过', act: [MINI('示例')],
      expect: ['通过', '号段 138'] },
    { desc: '「清空」回到等待输入', act: [MINI('清空')],
      expect: ['等待输入', '当前类型 手机号'], forbid: ['号段 138'] },
    { desc: '顶部 PkSeg 点「银行卡」能切类型', act: [SEG('银行卡')],
      expect: ['当前类型 银行卡'], forbid: ['当前类型 手机号'] },

    { desc: '身份证：示例通过并解析出生日期/性别/年龄', act: [TYPE('身份证'), MINI('示例')],
      expect: ['通过', '出生日期 1990-03-07', '性别 男', '年龄', '校验位 3'] },
    { desc: '身份证：今年 12 月这种还没到的出生日期判不通过（原来印 -1 岁）', act: [[IN(0), '110101202612310011']],
      expect: ['不通过', '出生日期还在未来'], forbid: ['-1 岁', '年龄'] },
    { desc: '身份证：校验位错时报出应该是哪一位', act: [[IN(0), '110101199003077219']],
      expect: ['不通过', '校验位不匹配'] },

    { desc: '银行卡：示例通过，给归属行与卡组织', act: [TYPE('银行卡'), MINI('示例')],
      expect: ['通过', '归属行 工商银行', '卡组织 银联', '卡号长度 19 位'] },
    { desc: '银行卡：末位改一笔 Luhn 就不过', act: [[IN(0), '6222021234567890129']],
      expect: ['不通过', 'Luhn 校验未通过'] },

    { desc: '邮箱：域名标签以连字符开头判不通过（原来放过）', act: [TYPE('邮箱'), [IN(0), 'a@-abc.com']],
      expect: ['不通过', '域名格式不正确'] },
    { desc: '邮箱：用户名连续的点判不通过（原来放过）', act: [[IN(0), 'a..b@example.com']],
      expect: ['不通过', '用户名里的点不能在首尾或连续'] },
    { desc: '邮箱：正常地址通过', act: [[IN(0), 'hello@example.com']],
      expect: ['通过', '用户名 hello', '域名 example.com'] },

    { desc: '网址：端口 99999 判不通过（原来印格式正确）', act: [TYPE('网址'), [IN(0), 'https://example.com:99999/x']],
      expect: ['不通过', '端口应在 1-65535 之间，当前 99999'] },
    { desc: '网址：端口 0 同样判掉', act: [[IN(0), 'https://example.com:0/']],
      expect: ['不通过', '端口应在 1-65535 之间，当前 0'] },
    { desc: '网址：合法带端口的通过并回显端口与路径', act: [[IN(0), 'https://a.example.com:8080/p?q=1']],
      expect: ['通过', '协议 https', '主机 a.example.com', '端口 :8080', '路径 /p'] },
    // 本轮修的两处端口判据，都印在页面上，所以在这里盯渲染出来的那行字：
    // :abc 原来连冒号带字母整段落进路径、这一页印「格式正确」，拆解页却在抛错——两页结论相反。
    { desc: '网址：端口写成 :abc 判不通过，且跟拆解页同一句话（原来印格式正确）', act: [[IN(0), 'http://a.com:abc/']],
      expect: ['不通过', '「abc」不是端口号，冒号后面写数字，例如 :8080'], forbid: ['格式正确', '路径 :abc'] },
    { desc: '网址：六位端口 000080 报错点名原文，不许印成 Number 后的 80', act: [[IN(0), 'https://example.com:000080/x']],
      expect: ['不通过', '端口最多 5 位数字，你写的是 000080'], forbid: ['当前 80'] },
    { desc: '网址：空端口 a.com:/ 放行，冒号不漏进路径', act: [[IN(0), 'https://example.com:/x']],
      expect: ['通过', '端口 默认', '路径 /x'], forbid: ['路径 :/x'] },

    { desc: 'IPv4：0.0.0.0 是本网络（原来自己那份表报公网地址）', act: [TYPE('IPv4'), [IN(0), '0.0.0.0']],
      expect: ['通过', '类型 本网络'], forbid: ['公网地址'] },
    { desc: 'IPv4：100.64 段是运营商级 NAT', act: [[IN(0), '100.64.1.1']],
      expect: ['通过', '类型 运营商级 NAT'] },
    { desc: 'IPv4：255.255.255.255 是广播地址', act: [[IN(0), '255.255.255.255']],
      expect: ['通过', '类型 广播地址'] },
    { desc: 'IPv4：8.8.8.8 仍是公网地址', act: [[IN(0), '8.8.8.8']],
      expect: ['通过', '类型 公网地址'] },

    { desc: '车牌：教练车尾牌通过（原来判格式不正确）', act: [TYPE('车牌号'), [IN(0), '京A1234学']],
      expect: ['通过', '类型 教练车号牌'] },
    { desc: '车牌：警车尾牌', act: [[IN(0), '京A0123警']],
      expect: ['通过', '类型 警车号牌'] },
    { desc: '车牌：普通牌与新能源各自归位', act: [[IN(0), '京A12345']],
      expect: ['通过', '类型 普通号牌'] },
    { desc: '车牌：新能源八位', act: [[IN(0), '京AD12345']],
      expect: ['通过', '类型 新能源'] },

    { desc: '姓名：首尾间隔号判不通过（原来判通过）', act: [TYPE('中文姓名'), [IN(0), '·张三']],
      expect: ['不通过', '间隔号不能在首尾或连续'] },
    { desc: '姓名：中间间隔号是正常写法', act: [[IN(0), '买买提·阿吾江']],
      expect: ['通过', '字数 7'] },
    { desc: '姓名：不在姓氏表里就不硬说常见', act: [[IN(0), '张三']],
      expect: ['通过', '字数 2'], forbid: ['常见姓氏'] },

    { desc: '批量：五行手机号 2 过 3 不过', act: [TYPE('手机号'), [AREA(0), '13800138000\n13912345678\n123\nabc\n12800138000'], BTN('开始批量校验')],
      expect: ['总条数 5', '通过 2', '未通过 3', '号段不存在或不是常见号段'] },
  ],
}
