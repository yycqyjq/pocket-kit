/**
 * IP 计算器（id=ip）。这轮六处修的都是页面上那几行字：
 *   8.8.8.8/32 原来印「这就是网络地址本身，不能配给主机」而同页说它有 1 个可用地址；
 *   10.0.0.0/31 原来同时印「2 个可用地址」和「总共 2 个，含网络号和广播号」；
 *   255.255.255.255/32 原来按表里先后印「保留地址」，校验台却印「广播地址」；
 *   010.1.1.1 原来悄悄算成 10.1.1.1；10.0.0.0/100 原来报错指着那个正确的 IP；
 *   198.51.100.0/24、203.0.113.0/24 原来查不到段，界面上类型那行退化成「C 类」。
 *
 * 输入框按出现顺序：CIDR、拆分位数、起始、结束。拆分那个是 type=number，
 * 填字母本来就填不进去，所以「非数字位数」这类分支在这儿验不了，交 scripts/selftest/ip.test.mjs。
 */
import { IN, CHIP, BTN } from '../harness.mjs'

export default {
  name: 'ip',
  id: 'ip',
  height: 1600,
  check: async ({ page, ok }) => {
    const kinds = await page.evaluate(() =>
      [...document.querySelectorAll('input.uni-input-input')].map((e) => e.type + ':' + (e.placeholder || ''))
    )
    ok(kinds.length >= 4, '四个输入框都在（CIDR／拆分位数／起始／结束）：' + JSON.stringify(kinds))
  },
  steps: [
    { desc: '默认 192.168.1.10/24：概览给吸到网络号后的 254 台', act: [],
      expect: ['192.168.1.0/24', '254 个可用地址', '总地址数 256（含网络号和广播号）'] },

    { desc: '/32 不再说「不能配给主机」，总地址数也不提网络号广播号', act: [[IN(0), '8.8.8.8/32']],
      expect: ['8.8.8.8/32', '1 个可用地址', '总地址数 1（单个地址，就是它自己）'],
      forbid: ['不能配给主机', '含网络号和广播号'] },
    { desc: '/31 两个地址都能配（RFC 3021），两行话不再互相打脸', act: [[IN(0), '10.0.0.0/31']],
      expect: ['2 个可用地址', '总地址数 2（点对点链路，两个地址都能配主机）'],
      forbid: ['不能配给主机', '含网络号和广播号'] },
    { desc: '/24 的网络号那行警告还得在（不是把判据整个删掉）', act: [[IN(0), '192.168.1.0/24']],
      expect: ['这就是网络地址本身，不能配给主机', '总地址数 256（含网络号和广播号）'] },
    { desc: '/24 的广播号同样还标', act: [[IN(0), '192.168.1.255/24']],
      expect: ['这就是广播地址，不能配给主机'] },

    { desc: '255.255.255.255/32 类型说广播地址（原来按表里先后说保留地址）', act: [[IN(0), '255.255.255.255/32']],
      expect: ['地址类型 广播地址（受限广播）'], forbid: ['保留地址'] },
    { desc: '198.51.100.7 认得是文档示例（原来这页查不到段，类型那行退化成 C 类）', act: [[IN(0), '198.51.100.7']],
      expect: ['地址类型 文档示例（TEST-NET-2）'], forbid: ['地址类型 C 类'] },
    { desc: '203.0.113.7 同上', act: [[IN(0), '203.0.113.7']],
      expect: ['地址类型 文档示例（TEST-NET-3）'] },

    { desc: '010.1.1.1 直说不收前导 0，不悄悄换成 10.1.1.1', act: [[IN(0), '010.1.1.1']],
      expect: ['提示 第 1 段「010」有前导 0，请直接写 10'], forbid: ['网段概览', 'IP换算成整数'] },
    { desc: '/100 报错指着斜杠后那截（原来指着前面那个正确的地址）', act: [[IN(0), '10.0.0.0/100']],
      expect: ['掩码位数要在 0~32 之间'], forbid: ['IPv4 地址要写成四段'] },
    { desc: '/abc 点名写错的那截并给两种写法', act: [[IN(0), '10.0.0.0/abc']],
      expect: ['「abc」既不是掩码位数也不是点分掩码'] },
    { desc: '/024 不当八进制猜', act: [[IN(0), '10.0.0.0/024']],
      expect: ['「024」有前导 0，掩码位数直接写 24'] },
    { desc: '五段掩码报的是掩码', act: [[IN(0), '10.0.0.0/8.8.8.8.8']],
      expect: ['掩码要写成四段，当前 5 段'] },

    { desc: '拆 192.168.1.0/24 成 /26：四块、每块 62 台', act: [CHIP('192.168.1.0/24'), [IN(1), '26'], BTN('拆分')],
      expect: ['192.168.1.0/26 192.168.1.1 ~ 192.168.1.62 62 台', '192.168.1.64/26', '192.168.1.128/26', '192.168.1.192/26'] },
    { desc: '拆成不变更长的前缀要报错', act: [[IN(1), '24'], BTN('拆分')],
      expect: ['新掩码要大于原掩码（24）'] },

    { desc: '合并 10.0.0.0~10.0.0.5 得两段', act: [[IN(2), '10.0.0.0'], [IN(3), '10.0.0.5'], BTN('合并')],
      expect: ['10.0.0.0/30 10.0.0.4/31', '段数 2 段'] },
    { desc: '起止写反自己换回来', act: [[IN(2), '10.0.0.5'], [IN(3), '10.0.0.0'], BTN('合并')],
      expect: ['10.0.0.0/30 10.0.0.4/31', '段数 2 段'] },
    { desc: '区间里也用同一份四段判据', act: [[IN(3), '10.0.0.999'], BTN('合并')],
      expect: ['第 4 段最大 255，你写了 999'] },

    { desc: '内网速查的数量口径对得上', act: [],
      expect: ['约 1677 万个地址', '254 台设备', '1022 个地址'] },
  ],
}
