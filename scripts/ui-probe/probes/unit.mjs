/**
 * 单位换算（id=unit）。
 * 改了七处因子（市制丈/尺/寸、亩、液盎司、千米/时、节）与 data 的 base，并让换算严格查表，
 * 所以要在真页面上确认用户看得见的数字：1 丈 → 尺 印 10 而不是 10.000001、1 公顷 → 亩 印 15 而不是 14.999999。
 *
 * 覆盖面：界面只保留 6 位小数，所以节、千米/时、液盎司这三处因子从截断小数改成精确式，页面印的
 * 字一个都没变（1000 节 照旧 514.444444）—— 那三处只有 scripts/selftest/unit.test.mjs 的 close(±1e-15) 抓得住。
 * 探针真正盯的是市制（10.000001）、亩（14.999999）、里→丈（150.000002）这类第 7 位就露馅的。
 *
 * type="digit" 在 H5 渲染成 input[type=number]，字母根本打不进 fill —— 所以「请输入有效数字」
 * 这条分支在这一页由浏览器挡着，探针只能验到输入框类型，不再假装能填 'abc'。
 */
import { IN, SEG, SWAP, MINI, PICK } from '../harness.mjs'

export default {
  name: 'unit',
  id: 'unit',
  height: 1500,
  check: async ({ page, ok }) => {
    const t = await page.evaluate(() => document.querySelector('input.uni-input-input').type)
    ok(t === 'number', '数值框是 input[type=' + t + ']，非数字进不来')
  },
  steps: [
    { desc: '默认：长度 1 米 → 厘米', act: [], expect: ['1 米 = 100 厘米'], forbid: ['请输入有效数字'] },
    { desc: '1 丈 → 尺 印 10（截断成 3.3333333 会印 10.000001）', act: [PICK(0, '丈'), PICK(1, '尺'), [IN(0), '1']],
      expect: ['1 丈 = 10 尺'], forbid: ['10.000001'] },
    { desc: '同一状态下的全单位表三行', act: [], expect: ['尺 10 复制', '寸 100 复制', '米 3.333333 复制'], forbid: ['寸 100.000099'] },
    { desc: '1 里 → 丈：整条市制链闭合', act: [PICK(0, '里'), PICK(1, '丈')], expect: ['1 里 = 150 丈'], forbid: ['150.000002'] },
    { desc: '1 尺 → 寸', act: [PICK(0, '尺'), PICK(1, '寸')], expect: ['1 尺 = 10 寸'] },
    { desc: '切类别会把首尾单位重建（不残留上一个类别）', act: [SEG('面积')],
      expect: ['从 平方毫米 ⇄ 到 平方厘米'], forbid: ['从 丈', '⇄ 到 厘米'] },
    { desc: '面积：1 公顷 → 亩 印 15（666.6667 会印 14.999999）', act: [PICK(0, '公顷'), PICK(1, '亩')],
      expect: ['1 公顷 = 15 亩'], forbid: ['14.999999'] },
    { desc: '体积：1 美制加仑 → 液盎司 印 128', act: [SEG('体积'), PICK(0, '美制加仑'), PICK(1, '液盎司(美)')],
      expect: ['1 美制加仑 = 128 液盎司(美)'], forbid: ['127.999'] },
    { desc: '速度：1 米/秒 → 千米/时 印 3.6', act: [SEG('速度'), PICK(0, '米/秒'), PICK(1, '千米/时')],
      expect: ['1 米/秒 = 3.6 千米/时'], forbid: ['3.599999'] },
    { desc: '速度：1000 节 → 米/秒 印 514.444444（第 9 位的漂这里看不见，见文件头）', act: [PICK(0, '节'), PICK(1, '米/秒'), [IN(0), '1000']],
      expect: ['1000 节 = 514.444444 米/秒'] },
    { desc: '压力：1 标准大气压 → 毫米汞柱 印整 760（水银 ρgh 那档因子会印 759.999892）', act: [SEG('压力'), PICK(0, '标准大气压'), PICK(1, '毫米汞柱'), [IN(0), '1']],
      expect: ['1 标准大气压 = 760 毫米汞柱'], forbid: ['759.999892'] },
    { desc: '温度：切类别自动给 25，摄氏 → 华氏', act: [SEG('温度')],
      expect: ['25 摄氏度 = 77 华氏度', '开尔文 298.15 复制', '兰氏度 536.67 复制'] },
    { desc: '温度：-40 是摄氏华氏交点', act: [[IN(0), '-40']], expect: ['-40 摄氏度 = -40 华氏度'] },
    { desc: '⇄ 交换首尾，-40 交点反着走也一样', act: [SWAP()], expect: ['-40 华氏度 = -40 摄氏度'] },
    { desc: '温度：开尔文 → 摄氏给绝对零度', act: [PICK(0, '开尔文'), PICK(1, '摄氏度'), [IN(0), '0']],
      expect: ['0 开尔文 = -273.15 摄氏度'] },
    { desc: '数据：1 GB → 字节逐位准（base 从 b 改成 bit 后仍成立）', act: [SEG('数据'), PICK(0, 'GB'), PICK(1, '字节'), [IN(0), '1']],
      expect: ['1 GB = 1073741824 字节', '比特 8589934592 复制'] },
    { desc: '超大数值走科学计数法，不甩一长串假数字（1e20 GB = 1.073741824e29 字节）', act: [[IN(0), '100000000000000000000']],
      expect: ['1.0737e+29 字节', 'GB 1.0000e+20 复制'], forbid: ['107374182400000000000'] },
    { desc: '清空：结果行给破折号，上一串数不残留', act: [MINI('清空')], expect: ['= — 字节'], forbid: ['100000000000000000000', 'e+19'] },
    { desc: '切回长度，单位跟着类别重建', act: [SEG('长度')], expect: ['从 毫米 ⇄ 到 厘米'], forbid: ['GB'] },
  ],
}
