/**
 * 百分比计算（id=percent）。八种场景切换靠顶部 PkSeg，结果 hero 大数字 + 明细行都印在页面上：
 *   占比 25/200 = 12.5%、求部分 200 的 15% = 30、涨跌 100→118 = +18%、
 *   增减 100 增/减 15% = 115/85、多多少 120 比 100 多 20%、折扣 299 打 7 折 = 209.3、
 *   百分点 15% 与 10% 差 5 个点、税 113 含税 127.69 且切模式后反算回 100。
 * 边界：分母为 0、折扣率越界都要印「算不出来」的原因，不能印 NaN；清空后结果卡整块消失。
 * 期望值全部手算，不是抄模块输出。
 */
import { IN, SEG } from '../harness.mjs'

export default {
  name: 'percent',
  id: 'percent',
  height: 1600,
  steps: [
    { desc: '默认「占比」：25 是 200 的 12.5%，反过来 800%', act: [],
      expect: ['12.5%', '25 ÷ 200 × 100%', '25 占 200 的 12.5%', '200 是 25 的 800%'],
      forbid: ['NaN', 'undefined', '[object Object]'] },

    { desc: '切「求部分」：200 的 15% = 30，剩下 170', act: [SEG('求部分')],
      expect: ['30', '200 的 15%', '200 的 15% 是 30', '170（剩下的）', '200 × 15 ÷ 100'],
      forbid: ['NaN', 'undefined'] },

    { desc: '切「涨跌幅」：100 → 118 是 +18%', act: [SEG('涨跌幅')],
      expect: ['+18%', '上涨', '18（绝对变化量）', '1.18 倍', '从 100 到 118，上涨 18%'],
      forbid: ['NaN', 'undefined'] },

    { desc: '切「增减」：100 增 15% 得 115，减 15% 得 85', act: [SEG('增减')],
      expect: ['115', '100 增加 15%', '85', '100 增加 15% 是 115；减少 15% 是 85'],
      forbid: ['NaN', 'undefined'] },

    { desc: '切「多多少」：120 比 100 多 20%，并提醒基数', act: [SEG('多多少')],
      expect: ['多 20%', '相对比较', '120 比 100 多 20%', '基数是「比」字后面的那个数，别颠倒'],
      forbid: ['NaN', 'undefined'] },

    { desc: '切「折扣」：299 打 7 折实付 209.3，省 89.7', act: [SEG('折扣')],
      expect: ['209.3', '实付金额（打 7 折）', '省下', '89.7', '7 折', '原价 299，打 7 折，实付 209.3，省 89.7'],
      forbid: ['NaN', 'undefined'] },

    { desc: '切「百分点」：15% 与 10% 相差 5 个百分点', act: [SEG('百分点')],
      expect: ['+5 个百分点', '百分点差', '从 10%', '到 15%', '从 10% 变成 15%，相差 5 个百分点'],
      forbid: ['NaN', 'undefined'] },

    { desc: '切「税」不含税→含税：113 加 13% 税 = 127.69', act: [SEG('税')],
      expect: ['127.69', '含税合计', '税额', '14.69', '不含税 113', '113 × (1 + 13%)'],
      forbid: ['NaN', 'undefined'] },

    { desc: '税模式切「含税 → 不含税」：113 反算回 100', act: [SEG('含税 → 不含税')],
      expect: ['100', '不含税金额', '税额', '13', '113 ÷ (1 + 13%)', '含税 113，其中不含税 100，税 13'],
      forbid: ['NaN', 'undefined'] },

    { desc: '边界：占比分母填 0 → 印原因，不许印 NaN', act: [SEG('占比'), [IN(1), '0']],
      expect: ['算不出来', '分母不能为 0'],
      forbid: ['12.5%', 'NaN', 'undefined'] },

    { desc: '边界：折扣率填 120 越界 → 印原因', act: [SEG('折扣'), [IN(1), '120']],
      expect: ['算不出来', '折扣百分比要在 0~100 之间'],
      forbid: ['209.3', 'NaN', 'undefined'] },

    { desc: '清空第一格：结果卡整块消失，只剩场景卡', act: [[IN(0), '']],
      expect: ['算哪种', '原价'],
      forbid: ['实付金额', '算不出来', 'NaN'] },
  ],
}
