/**
 * Cron 表达式（id=cron）。盯页面上印出来的那几行字，不看模块返回值：
 *   默认 `0 9 * * 1-5` 的汇总句必须是「工作日 09:00」——不能把「只在工作日跑」说成每天；
 *   「每 5 分钟」（分钟段为步长写法）的「分钟」行要逐个列出 00、05…，汇总句点明「等 288 个时间点」；
 *   接下来 10 次执行的时间依赖当前时刻，不写死具体时刻，只验「分钟能被 5 整除」这条性质；
 *   段数不足 / L W # / 越界 / 清空 各自印出对应那句原因。
 */
import { IN, MINI, CHIP, BTN } from '../harness.mjs'

export default {
  name: 'cron',
  id: 'cron',
  height: 2400,
  steps: [
    { desc: '默认工作日表达式：汇总句点明「工作日」而不是每天', act: [],
      expect: ['工作日 09:00', '1-5 → 工作日', '0 → 00', '9 → 09'],
      forbid: ['undefined', 'NaN', '[object Object]'] },

    { desc: '点预设「每 5 分钟」：分钟行逐个列出，汇总点出 288 个时间点', act: [CHIP('每 5 分钟')],
      expect: ['00、05、10、15、20、25、30、35、40、45、50、55',
        '每天 00:00、00:05、00:10、00:15、00:20、00:25 等 288 个时间点'],
      // 下一次触发依赖当前时刻，只验「分钟是 5 的倍数」这条与时刻无关的性质
      expectRe: /第 1 次\s*\d{4}-\d{2}-\d{2} \d{2}:[0-5][05] 周[一二三四五六日]/,
      forbid: ['undefined', 'NaN'] },

    { desc: '手输 `0 12 * * *`：汇总句是每天 12:00', act: [[IN(0), '0 12 * * *']],
      expect: ['每天 12:00', '12 → 12'], forbid: ['undefined', 'NaN'] },

    { desc: '只有 4 段：说清现在有几段', act: [[IN(0), '*/5 * * *']],
      expect: ['需要 5 段（分 时 日 月 周），现在有 4 段'],
      forbid: ['等 288 个时间点', 'undefined', 'NaN'] },

    { desc: 'Quartz 专有的 L：明确说不支持，而不是算错', act: [[IN(0), '0 0 L * *']],
      expect: ['暂不支持 L / W / #'], forbid: ['undefined', 'NaN'] },

    { desc: '小时越界 25：报出取值范围与实际填的值', act: [[IN(0), '0 25 * * *']],
      expect: ['小时 段的取值范围是 0~23，填的是 25'], forbid: ['undefined', 'NaN'] },

    { desc: '清空：回到「请输入」而不是继续印上一次结果', act: [MINI('清空')],
      expect: ['请输入 Cron 表达式'], forbid: ['工作日 09:00', 'undefined', 'NaN'] },

    { desc: '可视化生成：默认「每天 9:00」生成 0 9 * * *', act: [BTN('生成表达式')],
      toast: '已生成：0 9 * * *', expect: ['每天 09:00'], forbid: ['undefined', 'NaN'] },
  ],
}
