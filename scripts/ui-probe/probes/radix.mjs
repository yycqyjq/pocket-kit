/**
 * 进制转换（id=radix）。结果行是六种进制并列印出来的，这里盯「互相对得上」：
 *   255（10 进制）→ 2/8/16/32/36 分别 11111111 / 377 / ff / 7v / 73；
 *   换成按 16 进制读 ff、按 2 进制读 11111111，都要回到 255，形成闭环；
 *   二进制视图里 255 的十六进制是 000000FF、有效位数 8 位，切 8 位宽后按位取反是 00000000；
 *   非法字符（2 进制里填 2）要印「含有不属于 2 进制的字符」，结果全变 —、二进制卡收起；
 *   「取负」给 -255 各进制带负号；字符编码 AB → 65 66；清空后二进制卡消失。
 * 期望值全部手算／独立核算过，不是抄模块输出。
 */
import { IN, MINI, SEG } from '../harness.mjs'

export default {
  name: 'radix',
  id: 'radix',
  height: 1800,
  check: async ({ page, ok }) => {
    const kinds = await page.evaluate(() => [...document.querySelectorAll('input.uni-input-input')].map((e) => e.type))
    ok(kinds.length === 2 && kinds[0] === 'text', '两个输入框、数字那个是文本框（才谈得上填非法字符）：' + JSON.stringify(kinds))
  },
  steps: [
    { desc: '按 10 进制读 255：六种进制全给对', act: [[IN(0), '255']],
      expect: ['2 进制', '11111111', '8 进制', '377', '10 进制', '255', '16 进制', 'ff', '32 进制', '7v', '36 进制', '73'],
      forbid: ['NaN', 'undefined', '[object Object]'] },

    { desc: '切按 16 进制读 ff：十进制回到 255（与上一步闭环）', act: [SEG('16 进制'), [IN(0), 'ff']],
      expect: ['11111111', '377', '255', 'ff', '7v', '73'],
      forbid: ['NaN', 'undefined'] },

    { desc: '切按 2 进制读 11111111：十六进制是 ff', act: [SEG('2 进制'), [IN(0), '11111111']],
      expect: ['11111111', '377', '255', 'ff', '7v', '73'],
      forbid: ['NaN', 'undefined'] },

    { desc: '非法：2 进制里填 2 → 报字符不合法，结果全 —、二进制卡收起', act: [[IN(0), '2']],
      expect: ['含有不属于 2 进制的字符'],
      forbid: ['11111111', '二进制视图', 'NaN', 'undefined'] },

    { desc: '「取负」：-255 各进制都带负号', act: [SEG('10 进制'), [IN(0), '255'], MINI('取负')],
      expect: ['-255', '-ff', '-377', '-11111111', '-7v', '-73'],
      forbid: ['NaN', 'undefined'] },

    { desc: '二进制视图：255 的十六进制 000000FF、有效位数 8 位', act: [[IN(0), '255']],
      expect: ['二进制视图', '00000000 00000000 00000000 11111111', '000000FF', '有效位数', '8 位'] },

    { desc: '位宽切 8 位：按 8 位补码 11111111，按位取反 00000000', act: [SEG('8 位')],
      expect: ['按 8 位无符号解读', '255', '按 8 位补码解读', '11111111', '按位取反', '00000000'],
      forbid: ['按 32 位无符号解读', 'NaN', 'undefined'] },

    { desc: '字符编码：AB → 65 66', act: [[IN(1), 'AB']],
      expect: ['ASCII 码', '65 66'],
      forbid: ['undefined', 'NaN'] },

    { desc: '清空：二进制视图卡消失，结果行回到 —', act: [MINI('清空')],
      expect: ['转换结果'],
      forbid: ['11111111', '000000FF', '二进制视图'] },
  ],
}
