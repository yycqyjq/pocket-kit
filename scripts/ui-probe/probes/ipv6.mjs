/**
 * IPv6 规范化（id=ipv6）。修的都是页面上那几行：
 *   2001:db8:::1 / :2001:db8::1 / 2001:db8::1: / ::: / 1:2:3:4:5:6:7::8 原来被悄悄收下，
 *     界面直接印出「规范化结果」和「逐组二进制」，等于给了个错答案；
 *   2001:db8::/32 原来「压缩写法」带 /32、「完整写法」把 /32 丢了，同一页两行说两个东西；
 *   ::192.168.1.1 类型说「IPv4 兼容地址」，可「等价 IPv4」那行根本不出现，两行打架；
 *   ::ffff:010.1.1.1 原来悄悄换算成 10.1.1.1（四段判据在 ip.js 只有一份，这儿没走）；
 *   2001:db8::/024 原来按十进制收成 24；光贴一个 1.2.3.4 只说「要有 8 组」，不指出去哪写。
 *
 * placeholder 里就有「完整写法」四个字，别拿它当判据——所以下面用「分组数」「逐组二进制」这些结果行。
 */
import { IN, CHIP, MINI } from '../harness.mjs'

export default {
  name: 'ipv6',
  id: 'ipv6',
  height: 1600,
  check: async ({ page, ok }) => {
    const kinds = await page.evaluate(() =>
      [...document.querySelectorAll('input.uni-input-input')].map((e) => e.type + ':' + (e.getAttribute('placeholder') || ''))
    )
    ok(kinds.length === 1, '输入框就一个：' + JSON.stringify(kinds))
    const chips = await page.evaluate(() => [...document.querySelectorAll('.quick-i')].map((e) => e.textContent))
    ok(chips.length === 7, '快捷芯片 7 个：' + JSON.stringify(chips))
  },
  steps: [
    { desc: '默认那串完整写法：展开、压缩、分组数三行都在', act: [],
      expect: ['完整写法 2001:0db8:0000:0000:0000:ff00:0042:8329', '压缩写法 2001:db8::ff00:42:8329', '分组数 8 组', '文档示例地址'] },

    { desc: '带 /32 的写法：完整写法不许把前缀丢了，并多一行前缀长度', act: [[IN(0), '2001:db8::/32']],
      expect: ['压缩写法 2001:db8::/32', '完整写法 2001:0db8:0000:0000:0000:0000:0000:0000/32', '前缀长度 /32'] },
    { desc: '/64 时同样带（两行的前缀同进同出）', act: [[IN(0), 'fe80::1/64']],
      expect: ['前缀长度 /64', '链路本地地址'] },

    { desc: 'IPv4 映射芯片：类型与「等价 IPv4」那行同时出现', act: [CHIP('IPv4 映射')],
      expect: ['IPv4 映射地址', '等价 IPv4 192.168.1.1'] },
    { desc: '兼容式 ::192.168.1.1 也得给等价 IPv4（原来类型说有、那行却不出现）', act: [[IN(0), '::192.168.1.1']],
      expect: ['IPv4 兼容地址', '等价 IPv4 192.168.1.1'] },
    { desc: '::1 是环回，不许说成「等价 IPv4 0.0.0.1」', act: [[IN(0), '::1']],
      expect: ['环回地址'], forbid: ['等价 IPv4'] },
    { desc: ':: 未指定地址同样不报等价 IPv4', act: [[IN(0), '::']],
      expect: ['未指定地址'], forbid: ['等价 IPv4'] },

    { desc: '::: 三个冒号：报错点名右侧那截，别再给一张结果卡', act: [[IN(0), ':::']],
      expect: ['提示 「::」右边的「:」不是合法的分组写法'], forbid: ['分组数', '逐组二进制'] },
    { desc: '2001:db8:::1 同上一条路子（原来悄悄当成 2001:db8::1）', act: [[IN(0), '2001:db8:::1']],
      expect: ['提示 「::」右边的「:1」不是合法的分组写法'], forbid: ['分组数'] },
    { desc: ':2001:db8::1 左边挂单冒号', act: [[IN(0), ':2001:db8::1']],
      expect: ['「::」左边的「:2001:db8」不是合法的分组写法'], forbid: ['分组数'] },
    { desc: '2001:db8::1: 尾巴挂单冒号', act: [[IN(0), '2001:db8::1:']],
      expect: ['「::」右边的「1:」不是合法的分组写法'], forbid: ['分组数'] },
    { desc: '1:2:3:4:5:6:7::8：:: 一组零都没省', act: [[IN(0), '1:2:3:4:5:6:7::8']],
      expect: ['「::」至少要省略一组零，你这两边已经有 8 组了'], forbid: ['分组数'] },
    { desc: 'fe80::1%eth0 的区域号不收', act: [[IN(0), 'fe80::1%eth0']],
      expect: ['「::」右边的「1%eth0」不是合法的分组写法'], forbid: ['分组数'] },

    { desc: '/024 不当十进制悄悄收下', act: [[IN(0), '2001:db8::/024']],
      expect: ['前缀长度要写成 0~128 的数字，例如 /64，你写了「024」'], forbid: ['分组数'] },
    { desc: '/129 越界点出那一截', act: [[IN(0), '2001:db8::/129']],
      expect: ['你写了「129」'] },
    { desc: '::ffff:010.1.1.1 走 ip.js 那份四段判据，不悄悄换成 10.1.1.1', act: [[IN(0), '::ffff:010.1.1.1']],
      expect: ['内嵌的 IPv4 不合法：第 1 段「010」有前导 0，请直接写 10'], forbid: ['等价 IPv4'] },
    { desc: '::ffff:1.2.3 半截点分写法拦住', act: [[IN(0), '::ffff:1.2.3']],
      expect: ['「::」右边的「ffff:1.2.3」不是合法的分组写法'], forbid: ['分组数'] },
    { desc: '光贴 1.2.3.4：说清这是 IPv4，并给出内嵌写法', act: [[IN(0), '1.2.3.4']],
      expect: ['这看起来是 IPv4 地址「1.2.3.4」，IPv6 里没有这种写法；要嵌进 IPv6 得用 ::ffff: 开头的形式'], forbid: ['分组数'] },

    { desc: '组播芯片点开是组播地址', act: [CHIP('组播')],
      expect: ['压缩写法 ff02::1', '组播地址'] },
    { desc: '逐组二进制那 128 位没写错', act: [[IN(0), '2001:db8::1']],
      expect: ['0010000000000001 0000110110111000 0000000000000000 0000000000000000 0000000000000000 0000000000000000 0000000000000000 0000000000000001'] },
    { desc: '清空之后结果卡都不在（只剩输入框和芯片）', act: [MINI('清空')],
      expect: ['读取剪贴板'], forbid: ['分组数', '逐组二进制', '等价 IPv4'] },
  ],
}
